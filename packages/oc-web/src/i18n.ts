let lang: Lang = 'fr';
try { lang = (localStorage.getItem('oc-langue') as Lang) || 'fr'; } catch { /* stockage indisponible */ }

export const langue = () => lang;
export function setLangue(l: Lang) {
  lang = l;
  try { localStorage.setItem('oc-langue', l); } catch { /* ignore */ }
  appliquerLangue();
}
export function appliquerLangue() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}
export const t = (k: Cle): string => (lang === 'ar' ? ar[k] : fr[k]);
export const nombre = (n: number) => (Math.round(n * 100) / 100).toLocaleString(lang === 'ar' ? 'ar-MA' : 'fr-FR');
